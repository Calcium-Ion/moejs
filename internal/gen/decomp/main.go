// Command decomp generates engine/decomp_tables.go, the character
// decomposition data of String.prototype.localeCompare: the
// Decomposition_Mapping field of UnicodeData.txt (canonical and
// compatibility mappings, one level each, with the compatibility tag) and
// the non-zero Canonical_Combining_Class values. Hangul syllables decompose
// algorithmically and are not listed.
//
// UnicodeData.txt is downloaded from unicode.org at generation time only
// (-cache keeps a local copy); the output is deterministic and committed.
// The version matches internal/gen/ucd.
//
// Usage (from engine/, see the go:generate line in collate.go):
//
//	go run ../internal/gen/decomp -o decomp_tables.go [-cache dir]
package main

import (
	"bufio"
	"bytes"
	"encoding/binary"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const version = "17.0.0"

const baseURL = "https://www.unicode.org/Public/" + version + "/"

// tags are the compatibility formatting tags in the order of the engine's
// decomp* constants (decomp.go); index 0 is a canonical mapping.
var tags = []string{
	"", "<font>", "<noBreak>", "<initial>", "<medial>", "<final>", "<isolated>", "<circle>", "<super>",
	"<sub>", "<vertical>", "<wide>", "<narrow>", "<small>", "<square>", "<fraction>", "<compat>",
}

var cacheDir string

func main() {
	out := flag.String("o", "decomp_tables.go", "output file")
	flag.StringVar(&cacheDir, "cache", "", "directory for downloaded UCD files (reused when present)")
	flag.Parse()

	var decomp, ccc []byte
	nextDecomp, nextCCC := rune(0), rune(0)
	var runLo, runHi, runClass rune = -1, -1, 0
	flush := func() {
		if runLo < 0 {
			return
		}
		ccc = binary.AppendUvarint(ccc, uint64(runLo-nextCCC))
		ccc = binary.AppendUvarint(ccc, uint64(runHi-runLo))
		ccc = append(ccc, byte(runClass))
		nextCCC = runHi + 1
		runLo = -1
	}
	entries := 0
	eachLine(fetch("ucd/UnicodeData.txt"), func(f []string) {
		c := parseHex(f[0])
		if class, err := strconv.Atoi(f[3]); err != nil {
			log.Fatalf("%s: bad combining class %q", f[0], f[3])
		} else if class != 0 {
			if runLo >= 0 && c == runHi+1 && rune(class) == runClass {
				runHi = c
			} else {
				flush()
				runLo, runHi, runClass = c, c, rune(class)
			}
		}
		if f[5] == "" {
			return
		}
		fields := strings.Fields(f[5])
		tag := 0
		if strings.HasPrefix(fields[0], "<") {
			tag = indexOf(tags, fields[0])
			if tag <= 0 {
				log.Fatalf("%s: unknown decomposition tag %s", f[0], fields[0])
			}
			fields = fields[1:]
		}
		decomp = binary.AppendUvarint(decomp, uint64(c-nextDecomp))
		decomp = append(decomp, byte(tag), byte(len(fields)))
		for _, h := range fields {
			decomp = binary.AppendUvarint(decomp, uint64(parseHex(h)))
		}
		nextDecomp = c + 1
		entries++
	})
	flush()

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/gen/decomp from the Unicode %s UCD; DO NOT EDIT.\n\n", version)
	b.WriteString("package engine\n\n")
	fmt.Fprintf(&b, "// ucdDecompositionCount is the number of entries in ucdDecompositions.\n")
	fmt.Fprintf(&b, "const ucdDecompositionCount = %d\n\n", entries)
	b.WriteString("// ucdDecompositions is the Decomposition_Mapping field of UnicodeData.txt\n")
	b.WriteString("// in code point order: per entry the uvarint gap from the previous code\n")
	b.WriteString("// point plus one, the tag (0 canonical, else a decomp* constant), the\n")
	b.WriteString("// mapping length and each mapped code point as a uvarint.\n")
	fmt.Fprintf(&b, "const ucdDecompositions = %s\n\n", quote(string(decomp)))
	b.WriteString("// ucdCombiningClasses holds the non-zero Canonical_Combining_Class values\n")
	b.WriteString("// as runs: the uvarint gap from the previous run's end plus one, the\n")
	b.WriteString("// uvarint run length minus one and the class byte.\n")
	fmt.Fprintf(&b, "const ucdCombiningClasses = %s\n", quote(string(ccc)))

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func indexOf(list []string, s string) int {
	for i, x := range list {
		if x == s {
			return i
		}
	}
	return -1
}

func fetch(path string) []byte {
	if cacheDir != "" {
		if b, err := os.ReadFile(filepath.Join(cacheDir, filepath.FromSlash(path))); err == nil {
			return b
		}
	}
	resp, err := http.Get(baseURL + path)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", path, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	if cacheDir != "" {
		p := filepath.Join(cacheDir, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(p, b, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	return b
}

func eachLine(data []byte, fn func(fields []string)) {
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if strings.TrimSpace(line) == "" {
			continue
		}
		fields := strings.Split(line, ";")
		for i := range fields {
			fields[i] = strings.TrimSpace(fields[i])
		}
		fn(fields)
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
}

func parseHex(s string) rune {
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		log.Fatalf("bad code point %q", s)
	}
	return rune(v)
}

func quote(data string) string {
	if data == "" {
		return `""`
	}
	var sb strings.Builder
	line := 0
	sb.WriteString("\"")
	for i := 0; i < len(data); i++ {
		c := data[i]
		var piece string
		switch {
		case c == '"' || c == '\\':
			piece = `\` + string(c)
		case c >= 0x20 && c < 0x7F:
			piece = string(c)
		default:
			piece = fmt.Sprintf(`\x%02x`, c)
		}
		if line+len(piece) > 100 {
			sb.WriteString("\" +\n\t\"")
			line = 0
		}
		sb.WriteString(piece)
		line += len(piece)
	}
	sb.WriteString("\"")
	return sb.String()
}
