// Command regcheck generates engine/interp_run_regcheck.go, the checked
// build of the interpreter loop: a copy of engine/interp_run.go whose run
// checks every access to a frame's registers. The fast run indexes them
// through an array with the register operands and no bounds checks
// (engine/interp.go, window), relying on bytecode.VerifyRegisters and
// bytecode.RegisterSpans; the copy compares each access with the
// layout RegisterSpans gives the instruction being run (or with the
// registers of the handler being entered), with NumRegs, and with the
// stack the window was taken from, and each pc it dispatches with the
// instruction starts of VerifyRegisters' walk, so a layout row that leaves
// out a register run touches, an opcode without a row, a window run kept
// across a move of the stack, or a jump into an instruction fails there
// (engine/regcheck.go). The generator refuses a run that uses its window
// other than by index, which the copy could not check.
//
// It is a copy rather than a variant of the same source because run's
// register allocation is fragile: the fast build stays the source as it is
// written. The copy builds with -tags moejsregcheck and the original
// without; TestGenerated keeps the copy current.
//
// Usage (from engine/, see the go:generate line in interp_run.go):
//
//	go run ../internal/gen/regcheck [-in interp_run.go] [-out interp_run_regcheck.go]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/scanner"
	"go/token"
	"log"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "interp_run.go", "the interpreter loop's source")
	out := flag.String("out", "interp_run_regcheck.go", "the checked copy")
	flag.Parse()
	src, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	gen, err := generate(src)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, gen, 0o644); err != nil {
		log.Fatal(err)
	}
}

const (
	fastTag    = "//go:build !moejsregcheck\n"
	checkedTag = "//go:build moejsregcheck\n"
	directive  = "//go:generate go run ../internal/gen/regcheck\n"
	header     = "// Code generated by go run ../internal/gen/regcheck from interp_run.go; DO NOT EDIT.\n\n"
	runStart   = "func (r *Realm) run("
)

// generate returns the checked copy of the interpreter loop's source. It
// fails when the source no longer has what the copy hooks into, so a
// change to run that would leave an access unchecked stops here.
func generate(src []byte) ([]byte, error) {
	s := string(src)
	if !strings.HasPrefix(s, fastTag) {
		return nil, fmt.Errorf("the source does not start with %q", fastTag)
	}
	s = checkedTag + strings.TrimPrefix(s, fastTag)
	if strings.Count(s, directive) != 1 {
		return nil, fmt.Errorf("the source has no %q", directive)
	}
	s = strings.Replace(s, directive, "", 1)

	i := strings.Index(s, runStart)
	if i < 0 {
		return nil, fmt.Errorf("no %q", runStart)
	}
	j := strings.Index(s[i:], "\n}\n")
	if j < 0 {
		return nil, fmt.Errorf("run does not end")
	}
	j += i + len("\n}\n")
	body, err := checkRun(s[i:j])
	if err != nil {
		return nil, err
	}
	if strings.Contains(s[:i]+s[j:], "st.window(") {
		return nil, fmt.Errorf("a function of interp_run.go other than run takes a window")
	}
	out, err := format.Source([]byte(header + s[:i] + body + s[j:]))
	if err != nil {
		return nil, fmt.Errorf("the copy does not format: %v", err)
	}
	return out, nil
}

// checkRun rewrites run's source: its registers are a *checkedRegs taken
// with newCheckedRegs and refresh instead of window, each regs[i] becomes
// (*regs.at(int(i))), and the loop tells regs the instruction it runs
// (dispatch) and the handler it enters (handler).
func checkRun(run string) (string, error) {
	if err := onlyIndexes(run); err != nil {
		return "", err
	}
	const first = "regs := st.window(base)"
	if strings.Count(run, first) != 1 {
		return "", fmt.Errorf("run takes its first window other than with %q", first)
	}
	run = strings.Replace(run, first, "regs := newCheckedRegs(st, base, code)", 1)
	run = strings.ReplaceAll(run, "st.window(base)", "regs.refresh()")
	if strings.Contains(run, "window(") {
		return "", fmt.Errorf("run takes a window other than with st.window(base)")
	}
	run, n, err := rewriteIndexes(run)
	if err != nil {
		return "", err
	}
	if n == 0 {
		return "", fmt.Errorf("run indexes no register")
	}
	run, err = insertLine(run, "ipc := pc", "regs.dispatch(insns, ipc)", true)
	if err != nil {
		return "", err
	}
	run, err = insertLine(run, "if h.Kind == bytecode.HandlerCatch {", "regs.handler(h)", false)
	if err != nil {
		return "", err
	}
	return run, nil
}

// onlyIndexes fails unless run uses its window only to index it, which
// the copy checks: every regs that is not a field (x.regs) is followed by
// [, or is assigned st.window(base), alone (regs := ...) or with the frame
// (regs, fr = ...). Anything else (regs passed to a function, converted to
// a pointer or compared) would reach the window past the checks.
func onlyIndexes(run string) error {
	type tok struct {
		t   token.Token
		lit string
	}
	var toks []tok
	var sc scanner.Scanner
	fs := token.NewFileSet()
	src := []byte(run)
	var scanErr error
	sc.Init(fs.AddFile("run", -1, len(src)), src, func(_ token.Position, msg string) { scanErr = fmt.Errorf("run does not scan: %s", msg) }, 0)
	for {
		_, t, lit := sc.Scan()
		if t == token.EOF {
			break
		}
		if t == token.SEMICOLON && lit == "\n" {
			continue
		}
		toks = append(toks, tok{t, lit})
	}
	if scanErr != nil {
		return scanErr
	}
	window := []tok{{token.IDENT, "st"}, {token.PERIOD, ""}, {token.IDENT, "window"}, {token.LPAREN, ""}, {token.IDENT, "base"}, {token.RPAREN, ""}}
	at := func(i int, want ...tok) bool {
		if i+len(want) > len(toks) {
			return false
		}
		for j, w := range want {
			if toks[i+j].t != w.t || w.lit != "" && toks[i+j].lit != w.lit {
				return false
			}
		}
		return true
	}
	for i, k := range toks {
		if k.t != token.IDENT || k.lit != "regs" || i > 0 && toks[i-1].t == token.PERIOD {
			continue
		}
		switch {
		case at(i+1, tok{t: token.LBRACK}):
		case at(i+1, append([]tok{{t: token.DEFINE}}, window...)...):
		case at(i+1, append([]tok{{t: token.COMMA}, {token.IDENT, "fr"}, {t: token.ASSIGN}}, window...)...):
		default:
			var ctx []string
			for _, c := range toks[i:min(i+4, len(toks))] {
				if c.lit != "" {
					ctx = append(ctx, c.lit)
				} else {
					ctx = append(ctx, c.t.String())
				}
			}
			return fmt.Errorf("run uses its window other than to index it (%s); the checked copy cannot check that", strings.Join(ctx, " "))
		}
	}
	return nil
}

// rewriteIndexes turns every regs[i] of src into (*regs.at(int(i))) and
// returns how many it rewrote.
func rewriteIndexes(src string) (string, int, error) {
	var b strings.Builder
	n := 0
	for {
		k := strings.Index(src, "regs[")
		if k < 0 {
			b.WriteString(src)
			return b.String(), n, nil
		}
		if k > 0 && isIdent(src[k-1]) {
			b.WriteString(src[:k+len("regs[")])
			src = src[k+len("regs["):]
			continue
		}
		depth, end := 1, -1
		for p := k + len("regs["); p < len(src); p++ {
			switch src[p] {
			case '[':
				depth++
			case ']':
				depth--
			}
			if depth == 0 {
				end = p
				break
			}
		}
		if end < 0 {
			return "", 0, fmt.Errorf("an unclosed regs[ index")
		}
		index := src[k+len("regs[") : end]
		if strings.Contains(index, ":") {
			return "", 0, fmt.Errorf("run slices its registers (regs[%s]); the checked copy cannot", index)
		}
		b.WriteString(src[:k])
		b.WriteString("(*regs.at(int(" + index + ")))")
		src = src[end+1:]
		n++
	}
}

func isIdent(c byte) bool {
	return c == '_' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '.'
}

// insertLine inserts code on a line of its own after (or before) the only
// line of src whose trimmed text is anchor, at its indentation.
func insertLine(src, anchor, code string, after bool) (string, error) {
	lines := strings.SplitAfter(src, "\n")
	at := -1
	for i, l := range lines {
		if strings.TrimSpace(l) == anchor {
			if at >= 0 {
				return "", fmt.Errorf("two lines %q in run", anchor)
			}
			at = i
		}
	}
	if at < 0 {
		return "", fmt.Errorf("no line %q in run", anchor)
	}
	l := lines[at]
	indent := l[:len(l)-len(strings.TrimLeft(l, "\t "))]
	ins := indent + code + "\n"
	var b bytes.Buffer
	for i, l := range lines {
		if i == at && !after {
			b.WriteString(ins)
		}
		b.WriteString(l)
		if i == at && after {
			b.WriteString(ins)
		}
	}
	return b.String(), nil
}
