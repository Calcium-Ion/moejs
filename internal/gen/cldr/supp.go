package main

// The tables of engine/intl_supp_tables.go: the locales with number and date
// data and the locales they make available, the numbering systems with
// simple digit mappings, and the supplemental data of the Intl.Locale info
// methods and of the hour cycles of Intl.DateTimeFormat.

import (
	"bytes"
	"fmt"
	"log"
	"path"
	"slices"
	"strings"
)

func (g *gen) emitSupp(files map[string][]byte) []byte {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("// Code generated by internal/gen/cldr from CLDR %s; DO NOT EDIT.\n\n", version)
	p("%s", notice)
	p("package engine\n\n")

	avail := g.dataAvailable()
	p("// intlDataLocales lists the locales with number and date data, ','-separated,\n")
	p("// in the order of their data indexes.\n")
	p("const intlDataLocales = %q\n\n", strings.Join(dataLocales, ","))
	p("// intlDataLocaleCount is the number of data locales.\n")
	p("const intlDataLocaleCount = %d\n\n", len(dataLocales))
	d := g.locales
	var subs strings.Builder
	for _, i := range d.subs() {
		fmt.Fprintf(&subs, "%s>%s;", d.tags[i], index36(d.parent[i]))
	}
	p("// intlSubLocaleCount is the number of regional locales with data of their\n")
	p("// own.\n")
	p("const intlSubLocaleCount = %d\n\n", len(d.subs()))
	p("// intlDataIndexCount is the number of data indexes: the data locales',\n")
	p("// then the regional locales'.\n")
	p("const intlDataIndexCount = intlDataLocaleCount + intlSubLocaleCount\n\n")
	p("// intlSubLocales lists the regional locales of the data locales' languages\n")
	p("// whose data differs from their parent's, by CLDR's parent locales, in the\n")
	p("// order of their data indexes (from intlDataLocaleCount), as \"tag>parent;\":\n")
	p("// parent is the data index of the nearest ancestor with data (two base-36\n")
	p("// digits), of whose records the regional locale's are deltas.\n")
	p("const intlSubLocales = %s\n\n", quote(subs.String()))
	p("// intlDataAvailable lists the %d available locales of the constructors with\n", strings.Count(avail, ";"))
	p("// locale data: the CLDR locales of the data locales' languages that inherit\n")
	p("// a data locale's data, by CLDR's parent locales from the locale or from\n")
	p("// the locale with its likely script when that is not its language's (zh-HK:\n")
	p("// zh-Hant-HK), as \"tag>index;\" sorted by tag, index being the data index\n")
	p("// of the locale whose data it has, itself or its nearest ancestor with data\n")
	p("// (two base-36 digits).\n")
	p("const intlDataAvailable = %s\n\n", quote(avail))

	p("// intlNumberingDigits lists the numbering systems with simple digit mappings\n")
	p("// (numberingSystems.xml, type numeric) as \"id:0123456789;\" with the digits in\n")
	p("// UTF-8, sorted by id.\n")
	p("const intlNumberingDigits = %s\n\n", quote(g.numberingDigits(files)))

	p("// intlHourData is timeData of supplementalData.xml: \"key:preferred allowed...;\"\n")
	p("// where key is a region or a language_region, sorted by key.\n")
	p("const intlHourData = %s\n\n", quote(g.timeData(files)))

	week := g.weekData(files)
	p("// intlWeekData is weekData of supplementalData.xml: firstDay, weekendStart,\n")
	p("// weekendEnd and minDays, each as \"value:REGION REGION ...;\" records\n")
	p("// (a day 1 Monday to 7 Sunday, minDays its count) whose first record is\n")
	p("// the default (region 001), the groups separated by '|'.\n")
	p("const intlWeekData = %s\n\n", quote(week))

	p("// intlCollations lists the collation types of the locales of\n")
	p("// common/collation (and of those with a collation parent) as BCP 47\n")
	p("// keyword values without standard, search, the private and the\n")
	p("// unconfirmed or provisional ones, inherited ones included:\n")
	p("// \"tag:type type ...;\" sorted by tag.\n")
	p("const intlCollations = %s\n\n", quote(g.collations(files)))

	p("// intlDefaultNumbering lists the default numbering system of each data\n")
	p("// locale, ','-separated, in data index order (a regional locale's is its\n")
	p("// data locale's).\n")
	p("const intlDefaultNumbering = %q\n\n", g.defaultNumbering())

	p("// intlRTLScripts lists the scripts written right to left\n")
	p("// (scriptMetadata.txt), four letters each, sorted.\n")
	p("const intlRTLScripts = %q\n", g.rtlScripts(files))
	return b.Bytes()
}

// icuScriptAliases are the language-region locales ICU 78 aliases to the
// locale with the language's likely script, which CLDR has: zh_SG is
// zh_Hans_SG. ICU has no zh_MY alias, so zh-MY has zh's data, not
// zh_Hans_MY's (which zh-Hans-MY has).
var icuScriptAliases = map[string]bool{"zh_SG": true}

// index36 returns a data index as two base-36 digits.
func index36(i int) string {
	const digits = "0123456789abcdefghijklmnopqrstuvwxyz"
	if i >= 36*36 {
		log.Fatal("more data indexes than two base-36 digits")
	}
	return string([]byte{digits[i/36], digits[i%36]})
}

// dataAvailable returns intlDataAvailable.
func (g *gen) dataAvailable() string {
	index := map[string]int{} // CLDR id → data index
	for _, tag := range dataLocales {
		if g.ldml.file(cldrID(tag)) == nil {
			log.Fatalf("data locale %s has no common/main file", tag)
		}
	}
	for id, i := range g.locales.index {
		index[id] = i
	}
	isDefault := map[string]bool{}
	for _, id := range g.defaultContent {
		isDefault[id] = true
	}
	// A data locale that is the default content of its parent gives the
	// parent its data (zh-Hans → zh), and so on up.
	for changed := true; changed; {
		changed = false
		for id, i := range index {
			if isDefault[id] {
				if p := g.ldml.parent(id); p != "root" && p != "" {
					if _, ok := index[p]; !ok {
						index[p] = i
						changed = true
					}
				}
			}
		}
	}
	// The default content of a locale with data shares it (en → en_US).
	for changed := true; changed; {
		changed = false
		for _, id := range g.defaultContent {
			if _, ok := index[id]; ok {
				continue
			}
			if i, ok := index[g.ldml.parent(id)]; ok {
				index[id] = i
				changed = true
			}
		}
	}
	// Every available locale of a data locale's language that inherits its
	// data: by CLDR's parent locales from the locale, or from the locale
	// with its likely script when that is not its language's (zh-HK is
	// zh-Hant-HK, a child of zh-Hant).
	likelyScript := func(id langID) string { return g.maximize(id).script }
	tags := map[string]int{}
	for lang, rests := range g.available {
		for _, rest := range rests {
			tag := lang
			if rest = strings.TrimPrefix(rest, "-"); rest != "" {
				tag += "-" + rest
			}
			lid, ok := parseLangID(cldrID(tag))
			if !ok {
				log.Fatalf("available locale %s", tag)
			}
			// The locale with its likely script when that is not its
			// language's (zh-HK is zh-Hant-HK), or where ICU has an alias
			// (zh-SG is zh-Hans-SG).
			if lid.script == "" {
				if sc := likelyScript(lid); sc != likelyScript(langID{lang: lid.lang}) || icuScriptAliases[cldrID(tag)] {
					lid.script = sc
				}
			}
			// A language_Script with a script that is not the language's
			// likely one has root for parent (parentLocales' rule
			// nonlikelyScript): zh-Latn has no data.
			nonlikely := ""
			if lid.script != "" && lid.script != likelyScript(langID{lang: lid.lang}) {
				nonlikely = lid.lang + "_" + lid.script
			}
			for p := cldrID(lid.String()); p != "" && p != "root"; p = g.ldml.parent(p) {
				if i, ok := index[p]; ok {
					tags[tag] = i
					break
				}
				if p == nonlikely {
					break
				}
			}
		}
	}
	var out strings.Builder
	for _, tag := range sortedKeys(tags) {
		fmt.Fprintf(&out, "%s>%s;", tag, index36(tags[tag]))
	}
	return out.String()
}

// maximize adds the likely subtags to a language id (UTS #35 §4.4,
// without the alias step: the ids it serves are canonical).
func (g *gen) maximize(id langID) lsr {
	in := lsr{id.lang, id.script, id.region}
	for _, k := range []lsr{in, {in.lang, "", in.region}, {in.lang, in.script, ""}, {in.lang, "", ""}, {"", in.script, ""}} {
		if k.lang == "" && k.script == "" {
			continue
		}
		if to, ok := g.likely[k]; ok {
			out := to
			if in.lang != "" {
				out.lang = in.lang
			}
			if in.script != "" {
				out.script = in.script
			}
			if in.region != "" {
				out.region = in.region
			}
			return out
		}
	}
	return in
}

// numberingDigits returns intlNumberingDigits.
func (g *gen) numberingDigits(files map[string][]byte) string {
	var recs []string
	eachElement(files["common/supplemental/numberingSystems.xml"], "numberingSystem", func(attr func(string) string) {
		if attr("type") != "numeric" {
			return
		}
		if n := len([]rune(attr("digits"))); n != 10 {
			log.Fatalf("numbering system %s has %d digits", attr("id"), n)
		}
		recs = append(recs, attr("id")+":"+attr("digits")+";")
	})
	slices.Sort(recs)
	return strings.Join(recs, "")
}

// timeData returns intlTimeData.
func (g *gen) timeData(files map[string][]byte) string {
	m := map[string]string{}
	eachElement(files["common/supplemental/supplementalData.xml"], "hours", func(attr func(string) string) {
		for _, key := range strings.Fields(attr("regions")) {
			if _, dup := m[key]; dup {
				log.Fatalf("timeData %s twice", key)
			}
			m[key] = attr("preferred") + " " + attr("allowed")
		}
	})
	var out strings.Builder
	for _, k := range sortedKeys(m) {
		out.WriteString(k + ":" + m[k] + ";")
	}
	return out.String()
}

// weekData returns intlWeekData.
func (g *gen) weekData(files map[string][]byte) string {
	days := map[string]string{"mon": "1", "tue": "2", "wed": "3", "thu": "4", "fri": "5", "sat": "6", "sun": "7"}
	var groups []string
	for _, el := range []string{"firstDay", "weekendStart", "weekendEnd", "minDays"} {
		var recs []string
		def := ""
		eachElement(files["common/supplemental/supplementalData.xml"], el, func(attr func(string) string) {
			if attr("alt") != "" {
				return
			}
			v := attr("count")
			if el != "minDays" {
				v = days[attr("day")]
			}
			regions := strings.Fields(attr("territories"))
			if i := slices.Index(regions, "001"); i >= 0 {
				def = v
				regions = slices.Delete(regions, i, i+1)
			}
			if len(regions) > 0 {
				recs = append(recs, v+":"+strings.Join(regions, " ")+";")
			}
		})
		if def == "" {
			log.Fatalf("weekData %s without 001", el)
		}
		groups = append(groups, def+":;"+strings.Join(recs, ""))
	}
	return strings.Join(groups, "|")
}

// collations returns intlCollations.
func (g *gen) collations(files map[string][]byte) string {
	// CLDR's collation type names to their BCP 47 values.
	bcp := map[string]string{}
	eachElement(files["common/bcp47/collation.xml"], "type", func(attr func(string) string) {
		for _, a := range strings.Fields(attr("alias")) {
			bcp[a] = attr("name")
		}
	})
	types := map[string][]string{} // CLDR id → its own types
	for p, b := range files {
		if !strings.HasPrefix(p, "common/collation/") {
			continue
		}
		id := strings.TrimSuffix(path.Base(p), ".xml")
		var list []string
		eachElement(b, "collation", func(attr func(string) string) {
			t := attr("type")
			if v, ok := bcp[t]; ok {
				t = v
			}
			if d := attr("draft"); d == "unconfirmed" || d == "provisional" {
				return
			}
			if t == "standard" || t == "search" || strings.HasPrefix(t, "private-") || slices.Contains(list, t) {
				return
			}
			list = append(list, t)
		})
		types[id] = list
	}
	root := types["root"]
	// The locales whose collation parent is not their truncation (yue →
	// zh_Hant) inherit their parent's types even without a file.
	ids := map[string]bool{}
	for id := range types {
		ids[id] = true
	}
	for id := range g.ldml.compParents["collations"] {
		ids[id] = true
	}
	var out strings.Builder
	for _, id := range sortedKeys(ids) {
		if id == "root" {
			continue
		}
		set := slices.Clone(root)
		for p := id; p != "root" && p != ""; p = g.ldml.compParent("collations", p) {
			for _, t := range types[p] {
				if !slices.Contains(set, t) {
					set = append(set, t)
				}
			}
		}
		slices.Sort(set)
		out.WriteString(strings.ReplaceAll(id, "_", "-") + ":" + strings.Join(set, " ") + ";")
	}
	slices.Sort(root)
	return "root:" + strings.Join(root, " ") + ";" + out.String()
}

// ownNumbering returns the defaultNumberingSystem of each file of
// common/main that has one, by CLDR id.
func (g *gen) ownNumbering() map[string]string {
	own := map[string]string{}
	for p, b := range g.ldml.files {
		if !strings.HasPrefix(p, "common/main/") {
			continue
		}
		i := bytes.Index(b, []byte("<defaultNumberingSystem>"))
		if i < 0 {
			continue
		}
		rest := b[i+len("<defaultNumberingSystem>"):]
		own[strings.TrimSuffix(path.Base(p), ".xml")] = string(rest[:bytes.IndexByte(rest, '<')])
	}
	return own
}

// numberingOf returns the default numbering system of a CLDR id.
func (g *gen) numberingOf(id string) string {
	for ; id != ""; id = g.ldml.parent(id) {
		if v, ok := g.in.defNu[id]; ok && v != "↑↑↑" {
			return v
		}
	}
	return "latn"
}

// defaultNumbering returns intlDefaultNumbering.
func (g *gen) defaultNumbering() string {
	var list []string
	for i := range dataLocales {
		list = append(list, g.locales.recs[i].numbering)
	}
	return strings.Join(list, ",")
}

// rtlScripts returns intlRTLScripts.
func (g *gen) rtlScripts(files map[string][]byte) string {
	var list []string
	for _, line := range strings.Split(string(files["common/properties/scriptMetadata.txt"]), "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		f := strings.Split(line, ";")
		if len(f) > 6 && strings.TrimSpace(f[6]) == "YES" {
			list = append(list, strings.TrimSpace(f[0]))
		}
	}
	if len(list) == 0 {
		log.Fatal("no right-to-left script in scriptMetadata.txt")
	}
	slices.Sort(list)
	return strings.Join(list, "")
}
