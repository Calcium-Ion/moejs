package main

// The -norm output: the Unicode normalization data of String.prototype.
// normalize (UAX #15) for engine/unicode_norm_tables.go, and with -normtest
// a trimmed copy of NormalizationTest.txt for the engine's tests.

import (
	"bytes"
	"compress/gzip"
	"encoding/binary"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strconv"
	"strings"
)

// Hangul syllables decompose and compose algorithmically (Unicode §3.12);
// they have no entries in the tables.
const (
	hangulSBase  = 0xAC00
	hangulSCount = 19 * 21 * 28
)

func isHangulSyllable(c rune) bool { return c >= hangulSBase && c < hangulSBase+hangulSCount }

// decomposition is one UnicodeData.txt decomposition mapping.
type decomposition struct {
	compat bool // tagged (<font>, <compat>, ...)
	cps    []rune
}

type normGen struct {
	ccc        map[rune]uint8
	raw        map[rune]decomposition
	exclusions set            // Full_Composition_Exclusion
	qc         map[string]set // "NFC_QC=M" -> set, Hangul syllables removed
}

func (n *normGen) load() {
	n.ccc = map[rune]uint8{}
	n.raw = map[rune]decomposition{}
	eachLine(fetch("ucd/UnicodeData.txt"), func(f []string) {
		c := parseHex(f[0])
		v, err := strconv.Atoi(f[3])
		if err != nil || v < 0 || v > 254 {
			log.Fatalf("%s: bad combining class %q", f[0], f[3])
		}
		if v != 0 {
			n.ccc[c] = uint8(v)
		}
		if m := f[5]; m != "" {
			var d decomposition
			if strings.HasPrefix(m, "<") {
				_, m, _ = strings.Cut(m, ">")
				d.compat = true
			}
			d.cps = parseSeq(m)
			n.raw[c] = d
		}
	})
	n.exclusions = newSet()
	n.qc = map[string]set{}
	eachLine(fetch("ucd/DerivedNormalizationProps.txt"), func(f []string) {
		lo, hi := parseRange(f[0])
		switch {
		case len(f) == 2 && f[1] == "Full_Composition_Exclusion":
			n.exclusions.add(lo, hi)
		case len(f) == 3 && strings.HasSuffix(f[1], "_QC"):
			k := f[1] + "=" + f[2]
			s := n.qc[k]
			if s == nil {
				s = newSet()
				n.qc[k] = s
			}
			for c := lo; c <= hi; c++ {
				if !isHangulSyllable(c) {
					s.add(c, c)
				}
			}
		}
	})
	// NFD_QC and NFKD_QC are not emitted: they are No exactly for the code
	// points with a canonical (any) decomposition, which the engine derives.
	for c := rune(0); c <= maxRune; c++ {
		d, ok := n.raw[c]
		if n.qc["NFD_QC=N"].has(c) != (ok && !d.compat) || n.qc["NFKD_QC=N"].has(c) != ok {
			log.Fatalf("%U: NFD_QC/NFKD_QC do not match the decomposition mappings", c)
		}
	}
	for _, k := range []string{"NFC_QC=M", "NFC_QC=N", "NFKC_QC=M", "NFKC_QC=N"} {
		if n.qc[k] == nil {
			log.Fatalf("%s not found", k)
		}
	}
}

func (n *normGen) emit() []byte {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("// Code generated by internal/gen/ucd -norm from the Unicode %s UCD; DO NOT EDIT.\n\n", version)
	p("package engine\n\n")
	p("// ucdNormVersion is the UCD version of the normalization tables.\n")
	p("const ucdNormVersion = %q\n\n", version)

	keys := make([]rune, 0, len(n.raw))
	for c := range n.raw {
		keys = append(keys, c)
	}
	slices.Sort(keys)
	// The combining classes and the one-level decomposition mappings are in
	// engine/decomp_tables.go (internal/gen/decomp); the engine expands the
	// full decompositions from those when it decodes the tables.
	var comp []byte
	next := rune(0)
	for _, c := range keys {
		d := n.raw[c]
		if d.compat || n.exclusions.has(c) {
			continue
		}
		// The engine gives composites class 0 and only composes with starters.
		if len(d.cps) != 2 || n.ccc[c] != 0 || n.ccc[d.cps[0]] != 0 {
			log.Fatalf("%U: primary composite that is not a starter pair", c)
		}
		comp = binary.AppendUvarint(comp, uint64(c-next))
		comp = binary.AppendUvarint(comp, uint64(d.cps[0]))
		comp = binary.AppendUvarint(comp, uint64(d.cps[1]))
		next = c + 1
	}
	p("// ucdCompositions lists the primary composites (canonical mappings not in\n")
	p("// Full_Composition_Exclusion): uvarint gap from the previous composite + 1\n")
	p("// and the two code points of its mapping as uvarints.\n")
	p("const ucdCompositions = %s\n\n", quote(string(comp)))

	p("// ucdQuickCheck holds the Maybe and No values of NFC_QC and NFKC_QC in\n")
	p("// decodeRanges format, Hangul syllables removed. NFD_QC and NFKD_QC are No\n")
	p("// exactly for the code points with a canonical (any) decomposition.\n")
	p("var ucdQuickCheck = [...]ucdTable{\n")
	for _, k := range sortedKeys(n.qc) {
		if strings.HasPrefix(k, "NFC_") || strings.HasPrefix(k, "NFKC_") {
			p("{%q, %s},\n", k, quote(encodeRanges(n.qc[k].ranges())))
		}
	}
	p("}\n")
	return b.Bytes()
}

// normTestFixture trims NormalizationTest.txt: comments and blank lines go,
// and a column equal to an earlier one is written as that column's number.
func normTestFixture() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# NormalizationTest-%s.txt trimmed by internal/gen/ucd -normtest: comments\n", version)
	b.WriteString("# are dropped and a column equal to an earlier one is its number (1-5).\n")
	for line := range strings.Lines(string(fetch("ucd/NormalizationTest.txt"))) {
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		switch {
		case line == "":
			continue
		case strings.HasPrefix(line, "@"):
			b.WriteString(line + "\n")
			continue
		}
		cols := strings.Split(line, ";")
		if len(cols) < 5 {
			log.Fatalf("NormalizationTest.txt: %q", line)
		}
		cols = cols[:5]
		for i := range cols {
			cols[i] = strings.TrimSpace(cols[i])
			if j := slices.Index(cols[:i], cols[i]); j >= 0 {
				cols[i] = strconv.Itoa(j + 1)
			}
		}
		b.WriteString(strings.Join(cols, ";") + "\n")
	}
	var z bytes.Buffer
	zw, err := gzip.NewWriterLevel(&z, gzip.BestCompression)
	if err != nil {
		log.Fatal(err)
	}
	zw.Write(b.Bytes())
	if err := zw.Close(); err != nil {
		log.Fatal(err)
	}
	return z.Bytes()
}

func writeNorm(out, testOut string) {
	var n normGen
	n.load()
	src, err := format.Source(n.emit())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	if testOut != "" {
		if err := os.WriteFile(testOut, normTestFixture(), 0o644); err != nil {
			log.Fatal(err)
		}
	}
}
